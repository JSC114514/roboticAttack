def as_yaml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    return str(value)


def write_yaml(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by scripts/experiments/generate_suite_clean_baseline_configs.py",
        "# Clean baseline only. Do not compare attacks until this clean run succeeds.",
    ]
    lines.extend(f"{key}: {as_yaml_value(value)}" for key, value in data.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_list(value: str) -> list[str]:
    if value.strip().lower() == "all":
        return SUITES
    selected = parse_views(value)
    unknown = [item for item in selected if item not in SUITES]
    if unknown:
        raise SystemExit(f"Unknown suites {unknown}; allowed={SUITES}")
    return selected


def resolve_path(value: str) -> Path:
    path = Path(value).expanduser()
    return path if path.is_absolute() else PROJECT_ROOT / path


def has_any(path: Path, patterns: list[str]) -> bool:
    return any(any(path.glob(pattern)) for pattern in patterns)


def missing_indexed_shards(path: Path) -> list[str]:
    index_path = path / "model.safetensors.index.json"
    if not index_path.exists():
        return []
    try:
        data = json.loads(index_path.read_text(encoding="utf-8"))
    except Exception:
        return []
    shards = sorted(set(str(value) for value in data.get("weight_map", {}).values()))
    return [shard for shard in shards if not (path / shard).exists()]


