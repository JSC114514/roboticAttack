def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", default="configs/experiments/suite_model_paths.yaml")
    parser.add_argument("--suites", default="all")
    parser.add_argument("--include-missing", action="store_true", help="Generate configs even when model paths are TODO.")
    args = parser.parse_args()

    registry_path = Path(args.registry)
    if not registry_path.is_absolute():
        registry_path = PROJECT_ROOT / registry_path
    registry = read_simple_yaml(registry_path)
    suites = parse_list(args.suites)

    written: list[Path] = []
    skipped: list[str] = []
    for suite in suites:
        if args.include_missing or model_ready(registry, suite, "oft"):
            path = PROJECT_ROOT / "configs" / "experiments" / "suite_clean_baselines" / "m_series" / suite / f"M0_clean_{suite}.yaml"
            write_yaml(path, m0_config(registry, suite))
            written.append(path)
        else:
            skipped.append(f"{suite}:M0")
        if args.include_missing or model_ready(registry, suite, "oft_w"):
            path = PROJECT_ROOT / "configs" / "experiments" / "suite_clean_baselines" / "a_series" / suite / f"A0_clean_{suite}.yaml"
            write_yaml(path, a0_config(registry, suite))
            written.append(path)
        else:
            skipped.append(f"{suite}:A0")

    print(f"wrote {len(written)} config files")
    for path in written:
        print(path.relative_to(PROJECT_ROOT))
    if skipped:
        print("skipped missing model paths: " + ", ".join(skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
