def model_ready(registry: dict[str, str], suite: str, family: str) -> bool:
    checkpoint = registry.get(f"{suite}_{family}_model_checkpoint", "")
    subfolder = registry.get(f"{suite}_{family}_model_subfolder", "")
    if is_todo(checkpoint):
        return False
    if family == "oft_w" and is_todo(subfolder):
        return False
    model_dir = resolve_path(checkpoint)
    if subfolder.strip():
        model_dir = model_dir / subfolder.strip("/")
    if not model_dir.exists():
        return False
    required = ["config.json", "dataset_statistics.json"]
    if any(not (model_dir / rel_path).exists() for rel_path in required):
        return False
    if not has_any(model_dir, MODEL_WEIGHT_PATTERNS):
        return False
    if missing_indexed_shards(model_dir):
        return False
    if not has_any(model_dir, ["action_head--*_checkpoint.pt"]):
        return False
    if not has_any(model_dir, ["proprio_projector--*_checkpoint.pt"]):
        return False
    unnorm_key = registry.get(f"{suite}_unnorm_key", DEFAULT_UNNORM_KEYS[suite])
    try:
        stats = json.loads((model_dir / "dataset_statistics.json").read_text(encoding="utf-8"))
    except Exception:
        return False
    return unnorm_key in stats


