def as_yaml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    text = str(value)
    if text == "" or any(ch in text for ch in [": ", "#", "\n"]):
        return repr(text)
    return text


def write_yaml(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by scripts/experiments/generate_cross_dataset_transfer_configs.py",
        "# Cross-suite transfer eval: source patch is LIBERO-Spatial; patch is not retrained.",
        "# Target rollouts use the target suite model/statistics from suite_model_paths.yaml.",
    ]
    lines.extend(f"{key}: {as_yaml_value(value)}" for key, value in data.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def registry_value(registry: dict[str, str], key: str) -> str:
    value = str(registry.get(key, "")).strip()
    if not value:
        raise KeyError(f"Missing required registry key: {key}")
    return value


